def test_source_supplementary_information_rules() -> None:
    ok = validate_supplementary_information(valid_tex())
    assert ok["hard_errors"] == [] and ok["placed_after_references"] is True
    assert ok["substantive_element_count"] == 1
    cases = {
        valid_tex().replace("\\appendix\n", ""): r"paper.tex missing \appendix",
        valid_tex().replace(
            "\\section{Supplementary Information}\n", ""
        ): "missing Supplementary Information heading",
        valid_tex().replace(
            "\\clearpage\n\\appendix", "\\appendix"
        ): r"requires \clearpage between the bibliography",
        valid_tex().replace(
            "\\subsection{Extended evaluation details}\n", ""
        ): "at least one substantive subsection",
        valid_tex().replace(
            "We report additional",
            "Add supplementary material only when grounded artifacts support it. We report",
        ): "placeholder text",
        valid_tex().replace(
            "\\end{document}", "\\section{Extra}\nmore\n\\end{document}"
        ): "must be the final top-level section",
        valid_tex().replace(
            "\\end{document}", "\\input{x}\n\\end{document}"
        ): "must not import unchecked TeX files",
    }
    for tex, needle in cases.items():
        errors = validate_supplementary_information(tex)["hard_errors"]
        assert any(needle in error for error in errors), (needle, errors)


def test_commented_and_verbatim_text_is_not_structure() -> None:
    tex = "% \\appendix\n\\begin{verbatim}\n\\section{Supplementary Information}\n\\end{verbatim}\n"
    assert validate_supplementary_information(tex)["heading_present"] is False
    assert "Supplementary" not in mask_tex_verbatim(tex)
    assert "hidden" not in mask_false_conditionals("\\iffalse hidden \\fi shown")
    assert strip_false_conditionals("a\\iffalse b\\else c\\fi d") == "a c d"
    manuscript, supplement = split_manuscript_and_supplement(valid_tex())
    assert supplement is not None and supplement.startswith("\\appendix")
    assert "Supplementary Information" not in manuscript


