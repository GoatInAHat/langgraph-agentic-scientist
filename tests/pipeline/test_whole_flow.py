"""The whole method end to end on the package's own phase graphs, with scripted roles.

Unlike the other pipeline tests, nothing here replaces a phase: drafting (skipped, because the task
has a scaffold, as upstream skips it), investigation, ablations, the sealed final evaluation,
post-hoc analysis, the paper, the AI review and the revision all run their real graphs. Only the
models, the evaluators, the reference search and LaTeX are scripted or faked.
"""

from __future__ import annotations

from typing import Any

from langgraph.checkpoint.memory import InMemorySaver
from langgraph.store.memory import InMemoryStore
from testkit import thread
from whole_flow import context, unfilled_placeholders, write_task

from langgraph_agentic_scientist import LocalWorkspace, build_pipeline_graph
from langgraph_agentic_scientist.models import Role


async def test_the_whole_method_runs_on_its_own_phase_graphs(workspace: LocalWorkspace) -> None:
    task_dir = await write_task(workspace)
    ctx = context(workspace)
    app = build_pipeline_graph(checkpointer=InMemorySaver(), store=InMemoryStore())

    out: dict[str, Any] = await app.ainvoke({"task_dir": task_dir}, thread("whole"), context=ctx)

    statuses = {name: status.status for name, status in out["phase_status"].items()}
    assert statuses == {
        "task_drafting": "completed",
        "investigation": "completed",
        "downstream_selection": "skipped",
        "ablations": "completed",
        "final_evaluation": "completed",
        "posthoc": "completed",
        "paper": "completed",
        "review": "completed",
        "revision": "completed",
    }, out["phase_status"]
    assert out["status"] == "completed"
    assert out["investigation"].best is not None and out["investigation"].best.correct
    assert out["final"].outcome == "qualified"
    assert out["paper"].status == "complete"
    assert out["revision"].status == "promoted"

    models = ctx.models
    for role in (
        Role.IDEATOR,
        Role.CANDIDATE_AUTHOR,
        Role.VARIANT_GENERATOR,
        Role.VARIANT_EDITOR,
        Role.VARIANT_VERIFIER,
        Role.ANALYSIS_EXECUTOR,
        Role.REFERENCE_PLANNER,
        Role.PAPER_WRITER,
        Role.EVIDENCE_AUDITOR,
        Role.AI_REVIEWER,
        Role.AREA_CHAIR,
        Role.REVISION_WRITER,
    ):
        assert models.scripted(role).calls, f"{role} never ran"  # type: ignore[attr-defined]
    assert unfilled_placeholders(models) == {}  # type: ignore[arg-type]

    root = workspace.root
    assert (root / "task" / ".agentic_task_snapshot.json").is_file()
    paper_dir = root / out["paper"].paper_dir
    for name in ("paper.tex", "paper.pdf", "references.bib", "validation_report.json"):
        assert (paper_dir / name).is_file(), name
    # the writer's staged templates keep the watermark the paper phase put in them
    template = paper_dir / ".agents/skills/write-paper/templates/iclr/paper.tex"
    assert "Generated by The Agentic Scientist" in template.read_text()
