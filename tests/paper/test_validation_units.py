def layout(top: float, bottom: float, *, x: float = 100.0, width: float = 600.0) -> dict[str, Any]:
    fragment = {"text": "Body text", "x": x, "y": bottom, "font_size": top - bottom}
    return {
        "page_width": width,
        "page_height": 800.0,
        "page_x_min": 0.0,
        "page_x_max": width,
        "page_y_min": 0.0,
        "page_y_max": 800.0,
        "fragments": [fragment],
        "graphics": [],
    }


def test_the_last_body_page_fill_ratio_is_geometric() -> None:
    pages = [layout(700, 100), layout(700, 100), layout(400, 100)]
    assert compute_last_body_page_fill_ratio(
        pages, last_body_page_number=3, reference_start_page=None
    ) == pytest.approx(0.5)
    assert compute_last_body_page_fill_ratio(
        pages, last_body_page_number=1, reference_start_page=None
    ) == pytest.approx(1.0)
    assert (
        compute_last_body_page_fill_ratio([], last_body_page_number=1, reference_start_page=None)
        is None
    )
    two_columns = [
        {
            **layout(700, 100),
            "fragments": [{"text": "a", "x": 50.0, "y": 100.0, "font_size": 600.0}],
        },
        {
            **layout(700, 100),
            "fragments": [{"text": "a", "x": 50.0, "y": 400.0, "font_size": 300.0}],
        },
    ]
    ratio = compute_last_body_page_fill_ratio(
        two_columns, last_body_page_number=2, reference_start_page=None, body_columns=2
    )
    assert ratio == pytest.approx(0.25)


