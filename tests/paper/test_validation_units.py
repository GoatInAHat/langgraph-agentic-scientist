def test_input_hashes_cover_sources_styles_and_figures() -> None:
    from langgraph_agentic_scientist.workspace.protocol import FileEntry

    tex = valid_tex(include_graphics="figures/fig1").replace("{plain}", "{mystyle}")
    manifest = json.dumps({"figures": [{"path_png": "figures/fig1.png", "path_pdf": ""}]})
    files = {
        "paper.tex": add_watermark(tex),
        "mystyle.bst": "style",
        "references.bib": "bib",
        "figure_manifest.json": manifest,
        "figures/fig1.pdf": "pdf",
        "figures/fig1.png": "png",
    }
    entries = {
        name: FileEntry(path=name, size=len(text), sha256="sha256:" + name.encode().hex())
        for name, text in files.items()
    }
    entries["figures"] = FileEntry(path="figures", kind="dir")
    tree = SnapshotTree(entries, {name: text.encode() for name, text in files.items()})
    hashes = validation_input_sha256(tree)
    assert set(hashes) == {
        "paper.tex",
        "references.bib",
        "figure_manifest.json",
        "compile-input/mystyle.bst",
        "figure-asset/figures/fig1.pdf",
        "figure-asset/figures/fig1.png",
    }
    plain = SnapshotTree(entries, {**tree._contents, "paper.tex": tex.encode()})
    assert validation_input_sha256(plain)["paper.tex"] == hashes["paper.tex"]


# --- scope audit ---


def audit(**overrides: Any) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "shared_method_elements": ["the shared mechanism"],
        "scoped_method_elements": [
            {"element": "a", "scope": "setting one", "rationale": "r", "evidence_paths": ["x"]}
        ],
        "claims_requiring_scoping": [
            {
                "claim": "c",
                "scope": "s",
                "reason": "r",
                "required_paper_text": ["Scoped To Setting One"],
                "forbidden_unscoped_text": ["works everywhere"],
            }
        ],
        "manuscript_focus": {"shared_method_summary": "s", "scope_strategy": "t"},
    }
    payload.update(overrides)
    return payload


def audit_tree(payload: Any, tex: str, *, context: Any = None) -> SnapshotTree:
    files = {
        "paper.tex": tex,
        "method_scope_audit.json": payload if isinstance(payload, str) else json.dumps(payload),
        "method_scope_audit.md": "# audit",
    }
    if context is not None:
        files["paper_edit_context.json"] = json.dumps(context)
    return snapshot(files)


def test_the_method_scope_audit_rules() -> None:
    good = validate_method_scope_audit(audit_tree(audit(), "This is scoped   to setting ONE only."))
    assert good["ok"] and good["required_paper_text_hits"] == ["Scoped To Setting One"]
    missing = validate_method_scope_audit(audit_tree(audit(), "nothing"))
    assert "does not include required scoped text" in missing["hard_errors"][0]
    forbidden = validate_method_scope_audit(
        audit_tree(audit(), "scoped to setting one; but it works everywhere")
    )
    assert "still contains forbidden unscoped text" in forbidden["hard_errors"][0]
    assert not validate_method_scope_audit(audit_tree("{", "x"))["ok"]
    assert not validate_method_scope_audit(snapshot({"paper.tex": "x"}))["ok"]
    no_claims = validate_method_scope_audit(
        audit_tree(
            audit(claims_requiring_scoping=[]),
            "x",
            context={"edit_programs": [{"p": 1}], "old_programs": [{"p": 2}]},
        )
    )
    assert no_claims["ok"] and len(no_claims["soft_warnings"]) == 1
    odd = validate_method_scope_audit(audit_tree(audit(shared_method_elements=[]), "x"))
    assert "at least one shared_method_element" in odd["hard_errors"][0]
