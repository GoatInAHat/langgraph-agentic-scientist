def test_aux_and_recorder_validation() -> None:
    from langgraph_agentic_scientist.workspace.protocol import FileEntry

    def tree(files: dict[str, str], links: dict[str, str] | None = None) -> SnapshotTree:
        entries = {name: FileEntry(path=name, size=len(text)) for name, text in files.items()}
        for name, target in (links or {}).items():
            entries[name] = FileEntry(path=name, kind="symlink", target=target)
        return SnapshotTree(entries, {name: text.encode() for name, text in files.items()})

    good = tree({"paper.aux": "\\bibstyle{plain}\n\\bibdata{references}\n"})
    validate_bibtex_aux_dependencies(good)
    nested = tree(
        {"paper.aux": "\\@input{ch.aux}\n\\bibstyle{plain}\n", "ch.aux": "\\bibdata{references}\n"}
    )
    validate_bibtex_aux_dependencies(nested)
    with pytest.raises(RuntimeError, match="missing or unsafe"):
        validate_bibtex_aux_dependencies(tree({}))
    with pytest.raises(RuntimeError, match="escapes the paper workspace"):
        validate_bibtex_aux_dependencies(
            tree({"paper.aux": "\\@input{../x.aux}\n\\bibstyle{p}\n\\bibdata{references}"})
        )
    root = "/work/paper"
    files = tree({"paper.tex": "x", "figures/a.png": "x"}, {"link.tex": ".agents/skills/s/a.tex"})
    validate_latex_recorder_inputs(
        files, root=root, recorder_text=f"PWD {root}\nINPUT paper.tex\nINPUT {root}/figures/a.png\n"
    )
    with pytest.raises(RuntimeError, match="outside approved TeX roots"):
        validate_latex_recorder_inputs(
            files, root=root, recorder_text="INPUT /somewhere/else.tex\n"
        )
    with pytest.raises(RuntimeError, match="must not read staged agent skill files"):
        validate_latex_recorder_inputs(files, root=root, recorder_text="INPUT link.tex\n")
    with pytest.raises(RuntimeError, match="must not read staged agent skill files"):
        validate_latex_recorder_inputs(
            files, root=root, recorder_text=f"INPUT {root}/.agents/skills/x.sty\n"
        )


# --- evidence scan and tex dependencies ---


def snapshot(files: dict[str, str]) -> SnapshotTree:
    from langgraph_agentic_scientist.workspace.protocol import FileEntry

    entries = {name: FileEntry(path=name, size=len(text)) for name, text in files.items()}
    for name in list(entries):
        parent = Path(name).parent
        while parent.as_posix() != ".":
            entries.setdefault(parent.as_posix(), FileEntry(path=parent.as_posix(), kind="dir"))
            parent = parent.parent
    return SnapshotTree(entries, {name: text.encode() for name, text in files.items()})


def test_evidence_tokens_are_found_in_text_files_and_imports() -> None:
    tree = snapshot(
        {
            "paper.tex": "\\input{sections/a}\n",
            "sections/a.tex": "x @evidence[[r/a.json#/k]] y\n",
            "notes.txt": "@evidence[[r/ignored.json]]",
            "scripts/plot.py": "# @evidence[[r/b.json#/k]]\n",
            ".agents/skills/s/SKILL.md": "@evidence[[skip]]",
            "validation_feedback.md": "@evidence[[skip]]",
            "paper_prompt.md": "@evidence[[skip]]",
        }
    )
    found = scan_paper_for_evidence_tokens(tree)
    assert [(item["file"], item["line"]) for item in found] == [
        ("scripts/plot.py", 1),
        ("sections/a.tex", 1),
    ]
    assert paper_tex_dependency_paths(tree) == {"sections/a.tex"}


def test_tex_dependencies_refuse_dynamic_symlinked_and_skill_imports() -> None:
    with pytest.raises(RuntimeError, match="dynamic import target"):
        paper_tex_dependency_paths(snapshot({"paper.tex": "\\input{\\x}"}))
    with pytest.raises(RuntimeError, match="must not import agent skill files"):
        paper_tex_dependency_paths(snapshot({"paper.tex": "\\input{.agents/skills/a/b}"}))
    with pytest.raises(RuntimeError, match="escapes the paper workspace"):
        paper_tex_dependency_paths(snapshot({"paper.tex": "\\input{../x}"}))
    from langgraph_agentic_scientist.workspace.protocol import FileEntry

    linked = SnapshotTree(
        {
            "paper.tex": FileEntry(path="paper.tex", size=1),
            "a.tex": FileEntry(path="a.tex", kind="symlink", target="b.tex"),
            "b.tex": FileEntry(path="b.tex", size=1),
        },
        {"paper.tex": b"\\input{a}"},
    )
    with pytest.raises(RuntimeError, match="must not use symlinks"):
        paper_tex_dependency_paths(linked)


